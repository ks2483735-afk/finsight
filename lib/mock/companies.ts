export function getCompany(symbol: string): Company | undefined {
  const upper = symbol.trim().toUpperCase();
  return MOCK_UNIVERSE.find((c) => c.symbol === upper);
}

/** Resolve a free-text token to a company (symbol or name prefix). */
export function resolveSymbol(token: string): Company | undefined {
  const q = token.trim().toUpperCase();
  if (!q) return undefined;
  return (
    getCompany(q) ??
    MOCK_UNIVERSE.find((c) => c.name.toUpperCase().startsWith(q))
  );
}

export function companyToQuote(company: Company): Quote {
  return {
    symbol: company.symbol,
    name: company.name,
    exchange: company.exchange,
    region: company.region,
    price: company.price,
    currency: company.currency,
    change: company.change,
    changePercent: company.changePercent,
    timestamp: new Date().toISOString(),
    source: "mock",
    isMock: true,
  };
}

export function allQuotes(): Quote[] {
  return MOCK_UNIVERSE.map(companyToQuote);
}

export function quotesFor(symbols: string[]): { quotes: Quote[]; missing: string[] } {
  const quotes: Quote[] = [];
  const missing: string[] = [];
  for (const symbol of symbols) {
    const company = getCompany(symbol);
    if (company) quotes.push(companyToQuote(company));
    else missing.push(symbol);
  }
  return { quotes, missing };
}

export function indexQuotes(): Quote[] {
  return MOCK_INDICES.map((idx) => ({
    ...idx,
    timestamp: new Date().toISOString(),
    source: "mock",
    isMock: true,
  }));
}
